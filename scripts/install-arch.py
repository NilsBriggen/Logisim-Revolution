"""Repackage a published native DEB for pacman; no compilation or system Java."""

import argparse
import hashlib
import json
import os
import platform
import re
import shutil
import subprocess
import sys
import tempfile
import urllib.request
from datetime import datetime
from pathlib import Path

PROJECT_URL = "https://github.com/NilsBriggen/Logisim-Revolution"
RELEASES_API = "https://api.github.com/repos/NilsBriggen/Logisim-Revolution/releases"
ARCHITECTURES = {"x86_64": "amd64", "aarch64": "arm64"}
VERSION_PATTERN = r"[0-9]+\.[0-9]+\.[0-9]+(?:[a-zA-Z][a-zA-Z0-9.]*)?"
# DEB dependencies plus libraries used by the bundled JVM and desktop cache hooks.
DEPENDENCIES = (
    "glibc", "libbsd", "libmd", "libx11", "libxau", "libxcb", "libxdmcp",
    "libxext", "libxrender", "libxi", "libxtst", "alsa-lib", "fontconfig",
    "xdg-utils", "hicolor-icon-theme", "desktop-file-utils", "shared-mime-info",
)


PKGBUILD = r"""# Logisim-evolution - digital logic design tool and simulator
# Copyright by the Logisim-evolution developers
# https://github.com/logisim-evolution/
# This is free software released under GNU GPLv3 license
# Generated by scripts/install-arch.py from @SOURCE_URL@

pkgname=logisim-revolution-bin
pkgver=@PKGVER@
pkgrel=1
pkgdesc='Digital logic designer and simulator, with bundled Java runtime'
arch=('@ARCH@')
url='https://github.com/NilsBriggen/Logisim-Revolution'
license=('GPL-3.0-only')
depends=(@DEPENDS@)
makedepends=('libarchive')
provides=("logisim-revolution=$pkgver")
conflicts=('logisim-revolution')
options=('!strip' '!debug')
source=('@DEB@')
noextract=('@DEB@')
sha256sums=('@SHA256@')

package() {
  # Extract only the native payload. Debian maintainer scripts are never extracted
  # or run; Arch's existing desktop/icon/MIME transaction hooks handle registration.
  bsdtar -xOf "$srcdir/@DEB@" '@DATA_ARCHIVE@' > "$srcdir/data.tar"
  bsdtar --no-same-owner -xf "$srcdir/data.tar" -C "$pkgdir" ./opt/logisim-revolution

  local app="$pkgdir/opt/logisim-revolution"
  test -x "$app/bin/logisim-revolution"
  test -f "$app/lib/runtime/lib/server/libjvm.so"

  install -dm755 "$pkgdir/usr/bin" "$pkgdir/usr/share/applications"
  ln -s /opt/logisim-revolution/bin/logisim-revolution "$pkgdir/usr/bin/logisim-revolution"
  sed -e 's/^Name=.*/Name=Logisim Revolution/' \
      -e 's|^Exec=.*|Exec=/opt/logisim-revolution/bin/logisim-revolution %f|' \
      -e 's|^Icon=.*|Icon=logisim-revolution|' \
      -e 's/^Categories=.*/Categories=Education;Electronics;/' \
      -e 's|^MimeType=.*|MimeType=application/x-logisim-circuit;|' \
      "$app/lib/logisim-revolution-logisim-revolution.desktop" \
      > "$pkgdir/usr/share/applications/logisim-revolution.desktop"
  chmod 644 "$pkgdir/usr/share/applications/logisim-revolution.desktop"
  install -Dm644 "$app/lib/logisim-revolution.png" \
      "$pkgdir/usr/share/icons/hicolor/128x128/apps/logisim-revolution.png"
  install -Dm644 "$app/lib/application-x-logisim-circuit.png" \
      "$pkgdir/usr/share/icons/hicolor/128x128/mimetypes/application-x-logisim-circuit.png"
  install -Dm644 "$app/lib/logisim-revolution-logisim-revolution-MimeInfo.xml" \
      "$pkgdir/usr/share/mime/packages/logisim-revolution.xml"
}
"""


def fetch_page(page):
    request = urllib.request.Request(
        f"{RELEASES_API}?per_page=50&page={page}",
        headers={"Accept": "application/vnd.github+json", "User-Agent": "logisim-revolution-arch"},
    )
    with urllib.request.urlopen(request, timeout=60) as response:
        return json.load(response)


def select_release(tag=None):
    """Use publication time across all pages, including prereleases, never drafts."""
    published = []
    page = 1
    while True:
        releases = fetch_page(page)
        if not isinstance(releases, list):
            raise ValueError("GitHub did not return a release list.")
        if not releases:
            break
        for release in releases:
            if release.get("draft") is not False or not release.get("published_at"):
                continue
            if tag is None or release["tag_name"] == tag:
                published.append(release)
        page += 1
    if not published:
        raise ValueError(f"No published release found{f' for {tag}' if tag else ''}; drafts are excluded.")
    return max(published, key=lambda release: (
        datetime.fromisoformat(release["published_at"].replace("Z", "+00:00")),
        release["id"],
    ))


def package_version(version, tag):
    if tag != f"v{version}" or not re.fullmatch(r"[0-9]+\.[0-9]+\.[0-9]+", version):
        raise ValueError(f"Release tag {tag} does not match its package version {version}.")
    return version


def select_asset(release, arch):
    if arch not in ARCHITECTURES:
        raise ValueError(f"Unsupported architecture: {arch}; expected x86_64 or aarch64.")
    pattern = rf"logisim-revolution_({VERSION_PATTERN})_{ARCHITECTURES[arch]}\.deb"
    matches = [asset for asset in release.get("assets", [])
               if re.fullmatch(pattern, asset.get("name", ""))]
    if len(matches) != 1:
        raise ValueError(f"Release {release['tag_name']} must have exactly one {arch} DEB; found {len(matches)}.")
    asset = matches[0]
    version = re.fullmatch(pattern, asset["name"])[1]
    pkgver = package_version(version, release["tag_name"])
    expected_url = f"{PROJECT_URL}/releases/download/{release['tag_name']}/{asset['name']}"
    if asset.get("browser_download_url") != expected_url or asset.get("size", 0) <= 0:
        raise ValueError("DEB has an unexpected download URL or empty size.")
    return asset, pkgver


def check_dependencies(build_only):
    if os.geteuid() == 0:
        raise ValueError("Run this script as your normal user, without sudo; makepkg must not run as root.")
    commands = {
        "makepkg": "pacman", "pacman": "pacman", "bsdtar": "libarchive",
        "fakeroot": "fakeroot", "zstd": "zstd", "sha256sum": "coreutils",
    }
    missing = sorted({package for command, package in commands.items() if not shutil.which(command)})
    if missing:
        raise ValueError("Missing packaging tools. Install with: sudo pacman -S --needed " + " ".join(missing))
    if build_only:
        result = subprocess.run(["pacman", "-T", *DEPENDENCIES], capture_output=True, text=True)
        if result.returncode == 127:
            raise ValueError("Missing runtime dependencies. Install with: sudo pacman -S --needed "
                             + " ".join(result.stdout.split()))
        result.check_returncode()


def download(asset, destination):
    request = urllib.request.Request(asset["browser_download_url"],
                                     headers={"User-Agent": "logisim-revolution-arch"})
    with urllib.request.urlopen(request, timeout=120) as response, destination.open("wb") as output:
        shutil.copyfileobj(response, output)
    if destination.stat().st_size != asset["size"]:
        raise ValueError("Downloaded DEB size differs from the release metadata; refusing to package it.")


def write_pkgbuild(directory, asset, pkgver, arch):
    deb = directory / asset["name"]
    with deb.open("rb") as source:
        checksum = hashlib.file_digest(source, "sha256").hexdigest()
    members = subprocess.check_output(["bsdtar", "-tf", str(deb)], text=True).splitlines()
    data = [member for member in members if re.fullmatch(r"data\.tar(?:\.(?:xz|gz|zst|bz2))?", member)]
    if len(data) != 1:
        raise ValueError("DEB must contain exactly one supported data archive.")
    replacements = {
        "@PKGVER@": pkgver,
        "@ARCH@": arch,
        "@DEB@": asset["name"],
        "@SHA256@": checksum,
        "@DATA_ARCHIVE@": data[0],
        "@DEPENDS@": " ".join(f"'{dependency}'" for dependency in DEPENDENCIES),
        "@SOURCE_URL@": asset["browser_download_url"],
    }
    recipe = PKGBUILD
    for placeholder, value in replacements.items():
        recipe = recipe.replace(placeholder, value)
    (directory / "PKGBUILD").write_text(recipe, encoding="utf-8")
    print(f"DEB SHA256: {checksum}", flush=True)


def run_makepkg(directory, build_only):
    # Explicit destinations keep user makepkg settings from writing into the checkout
    # or sharing stale sources with another release bearing the same DEB filename.
    command = ["makepkg", "--clean"]
    if not build_only:
        command.append("-si")
    command.extend(f"{key}={directory}" for key in (
        "BUILDDIR", "PKGDEST", "SRCDEST", "SRCPKGDEST", "LOGDEST",
    ))
    command.append("PKGEXT=.pkg.tar.zst")
    subprocess.run(command, cwd=directory, check=True)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--build-only", action="store_true", help="build a package without installing anything")
    parser.add_argument("--tag", help="choose a published build-N-attempt-N tag instead of the newest release")
    args = parser.parse_args(argv)
    check_dependencies(args.build_only)
    arch = platform.machine()
    if platform.system() != "Linux" or arch not in ARCHITECTURES:
        raise ValueError("This installer requires x86_64 or aarch64 Arch Linux (or a derivative such as CachyOS).")
    release = select_release(args.tag)
    asset, pkgver = select_asset(release, arch)
    # mkdtemp creates a private directory; retain the package and recipe for inspection.
    directory = Path(tempfile.mkdtemp(prefix="logisim-revolution-arch-", dir="/tmp"))
    print(f"Release: {release['tag_name']} -> logisim-revolution-bin {pkgver}", flush=True)
    print(f"Build directory (retained): {directory}", flush=True)
    print(f"Downloading {asset['name']} ...", flush=True)
    download(asset, directory / asset["name"])
    write_pkgbuild(directory, asset, pkgver, arch)
    run_makepkg(directory, args.build_only)
    print(f"Package: {directory}/logisim-revolution-bin-{pkgver}-1-{arch}.pkg.tar.zst")
    if args.build_only:
        print("Build only: nothing installed. You can remove the printed build directory when finished.")
    else:
        print("Installed. Run logisim-revolution or open Logisim Revolution from your application menu.")


if __name__ == "__main__":
    try:
        main()
    except (ValueError, KeyError, OSError, subprocess.CalledProcessError) as error:
        print(f"Arch install failed: {error}", file=sys.stderr)
        sys.exit(1)
    except KeyboardInterrupt:
        sys.exit(130)
